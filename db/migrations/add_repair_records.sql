CREATE TABLE IF NOT EXISTS public.repair_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repaired_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    merchant_name TEXT NOT NULL CHECK (length(btrim(merchant_name)) > 0),
    business_number TEXT,
    card_company TEXT,
    installment_months INTEGER CHECK (installment_months >= 0),
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.repair_records IS '차량 수리 내역';
COMMENT ON COLUMN public.repair_records.repaired_at IS '실제 수리 날짜와 시각. 생략하면 현재 시각';
COMMENT ON COLUMN public.repair_records.merchant_name IS '상호명/대표자';
COMMENT ON COLUMN public.repair_records.business_number IS '사업자번호. 앞자리 0과 하이픈을 보존';
COMMENT ON COLUMN public.repair_records.card_company IS '카드사';
COMMENT ON COLUMN public.repair_records.installment_months IS '카드 할부 개월 수. 0은 일시불, NULL은 미입력';
COMMENT ON COLUMN public.repair_records.total_amount IS '수리 총액 (원)';

CREATE INDEX IF NOT EXISTS repair_records_repaired_at_id_idx
    ON public.repair_records (repaired_at, id);
