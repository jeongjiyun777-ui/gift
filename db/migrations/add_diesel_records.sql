CREATE TABLE IF NOT EXISTS public.diesel_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchased_on DATE NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    merchant_name TEXT NOT NULL CHECK (length(btrim(merchant_name)) > 0),
    business_number TEXT,
    card_company TEXT,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    liters NUMERIC(12, 3) NOT NULL CHECK (liters > 0),
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON COLUMN public.diesel_records.liters IS '영수증 수량 (리터, L)';
COMMENT ON COLUMN public.diesel_records.unit_price IS '부가세 포함 리터당 단가 (원)';
COMMENT ON COLUMN public.diesel_records.total_amount IS '서버에서 단가 × 수량으로 계산한 총액';
CREATE INDEX IF NOT EXISTS diesel_records_purchased_on_id_idx ON public.diesel_records (purchased_on, id);
