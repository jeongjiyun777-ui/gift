CREATE TABLE IF NOT EXISTS public.vehicle_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number TEXT NOT NULL UNIQUE CHECK (length(btrim(vehicle_number)) > 0),
    current_odometer_km NUMERIC(12, 1) NOT NULL CHECK (current_odometer_km >= 0),
    odometer_recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE public.vehicle_records IS '차량별 현재 누적 주행거리. 운행별 구간 거리와 별도 관리';
COMMENT ON COLUMN public.vehicle_records.current_odometer_km IS '차량 계기판 누적 주행거리(km), 소수 첫째 자리까지';
COMMENT ON COLUMN public.vehicle_records.odometer_recorded_at IS '누적 주행거리를 기록한 시각';
