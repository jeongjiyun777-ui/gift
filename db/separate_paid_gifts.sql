BEGIN;
LOCK TABLE public.gifts IN SHARE ROW EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS public.paid_gifts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT NOT NULL DEFAULT 'paid' CHECK (direction = 'paid'),
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    amount BIGINT NOT NULL CHECK (amount >= 0),
    category TEXT,
    detail TEXT,
    location TEXT,
    source_gift_id INTEGER UNIQUE
);

INSERT INTO public.paid_gifts (name, amount, category, detail, location, source_gift_id)
SELECT name, amount, category, detail, location, id FROM public.gifts
WHERE direction = 'paid' ORDER BY id
ON CONFLICT (source_gift_id) DO NOTHING;
DO $migration$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.gifts g LEFT JOIN public.paid_gifts p ON p.source_gift_id = g.id
        WHERE g.direction = 'paid' AND (p.id IS NULL
            OR p.name IS DISTINCT FROM g.name OR p.amount IS DISTINCT FROM g.amount
            OR p.category IS DISTINCT FROM g.category OR p.detail IS DISTINCT FROM g.detail
            OR p.location IS DISTINCT FROM g.location)
    ) THEN RAISE EXCEPTION '낸 금액 복사 검증 실패'; END IF;
END;
$migration$;
DELETE FROM public.gifts WHERE direction = 'paid';
COMMIT;
