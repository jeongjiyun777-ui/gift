CREATE TABLE gifts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT NOT NULL DEFAULT 'received' CONSTRAINT gifts_direction_check CHECK (direction IN ('received', 'paid')),
    category TEXT,
    detail TEXT,
    location TEXT,
    name TEXT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0)
);

CREATE INDEX gifts_direction_id_idx ON gifts (direction, id);

CREATE TABLE public.driving_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operated_on DATE NOT NULL
        DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    category TEXT,
    shipper_name TEXT NOT NULL CHECK (length(btrim(shipper_name)) > 0),
    region_1 TEXT,
    region_2 TEXT,
    shipping_line TEXT,
    km INTEGER CONSTRAINT driving_records_km_range CHECK (km BETWEEN 1 AND 9999),
    container_spec TEXT,
    container_no TEXT,
    charge_amount BIGINT NOT NULL CHECK (charge_amount >= 0),
    tax_amount BIGINT CHECK (tax_amount >= 0),
    memo TEXT,
    vehicle_number TEXT,
    recipient_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.paid_gifts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT NOT NULL DEFAULT 'paid' CHECK (direction = 'paid'),
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    amount BIGINT NOT NULL CHECK (amount >= 0),
    category TEXT,
    detail TEXT,
    location TEXT,
    source_gift_id INTEGER UNIQUE
);
