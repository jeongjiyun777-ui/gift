-- 전체 테이블 정의의 기준 파일입니다. 기존 DB 변경 이력은 migrations/에 보관합니다.
CREATE TABLE IF NOT EXISTS public.gifts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT NOT NULL DEFAULT 'received' CONSTRAINT gifts_direction_check CHECK (direction IN ('received', 'paid')),
    category TEXT,
    detail TEXT,
    location TEXT,
    name TEXT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0)
);

CREATE INDEX IF NOT EXISTS gifts_direction_id_idx ON public.gifts (direction, id);

CREATE TABLE IF NOT EXISTS public.driving_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operated_on DATE NOT NULL
        DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    category TEXT CONSTRAINT driving_records_category_check CHECK (category IN ('MT', 'FULL')),
    carrier_name TEXT NOT NULL CHECK (length(btrim(carrier_name)) > 0),
    shipper_name TEXT,
    region_1 TEXT,
    region_2 TEXT,
    shipping_line TEXT,
    departure_time TIME WITHOUT TIME ZONE,
    arrival_time TIME WITHOUT TIME ZONE,
    start_odometer_km BIGINT,
    pickup_odometer_km BIGINT,
    arrival_odometer_km BIGINT,
    odometer_recorded_at TIMESTAMPTZ,
    start_km INTEGER CONSTRAINT driving_records_start_km_range CHECK (start_km BETWEEN 1 AND 999),
    km INTEGER CONSTRAINT driving_records_km_range CHECK (km BETWEEN 1 AND 999),
    container_spec TEXT,
    container_no TEXT,
    charge_amount BIGINT NOT NULL CHECK (charge_amount >= 0),
    tax_amount BIGINT CHECK (tax_amount >= 0),
    memo TEXT,
    vehicle_number TEXT,
    recipient_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT driving_records_odometer_check CHECK ((start_odometer_km IS NULL AND pickup_odometer_km IS NULL AND arrival_odometer_km IS NULL) OR (start_odometer_km IS NOT NULL AND pickup_odometer_km IS NOT NULL AND arrival_odometer_km IS NOT NULL AND start_odometer_km >= 0 AND start_odometer_km <= pickup_odometer_km AND pickup_odometer_km <= arrival_odometer_km AND arrival_odometer_km <= 999999999))
);

CREATE TABLE IF NOT EXISTS public.paid_gifts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT NOT NULL DEFAULT 'paid' CHECK (direction = 'paid'),
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    amount BIGINT NOT NULL CHECK (amount >= 0),
    category TEXT,
    detail TEXT,
    location TEXT,
    paid_on DATE,
    source_gift_id INTEGER UNIQUE
);

CREATE TABLE IF NOT EXISTS public.urea_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchased_on DATE NOT NULL
        DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    merchant_name TEXT NOT NULL CHECK (length(btrim(merchant_name)) > 0),
    business_number TEXT,
    card_company TEXT,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    liters NUMERIC(12, 3) NOT NULL CHECK (liters > 0),
