-- 검토용 스키마: 현재 gift DB에 연결한 상태에서 승인 후 수동 실행하세요.
-- 기존 public.gifts(축의금)는 그대로 두고 public.driving_records(운행기록)만 생성합니다.
-- 이 파일은 자동 실행하지 않습니다. 개인정보나 이미지 데이터를 INSERT하지 않습니다.
BEGIN;

CREATE TABLE public.driving_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operated_on DATE NOT NULL
        DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    category TEXT,
    shipper_name TEXT NOT NULL CHECK (length(btrim(shipper_name)) > 0),
    region_1 TEXT,
    region_2 TEXT,
    shipping_line TEXT,
    km INTEGER CONSTRAINT driving_records_km_range CHECK (km BETWEEN 1 AND 9999),
    container_spec TEXT,
    container_no TEXT,
    charge_amount BIGINT NOT NULL CHECK (charge_amount >= 0),
    tax_amount BIGINT CHECK (tax_amount >= 0),
    memo TEXT,
    vehicle_number TEXT,
    recipient_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.driving_records IS '운행 거래명세서 내역. gift DB의 축의금 테이블 gifts와 별도 관리';
COMMENT ON COLUMN public.driving_records.id IS '자동 생성되는 고유 번호. 삭제된 번호는 재사용하거나 재정렬하지 않음';
COMMENT ON COLUMN public.driving_records.operated_on IS '원본 일자에 해당하는 실제 운행일. 생략하면 등록 당시 한국 날짜';
COMMENT ON COLUMN public.driving_records.category IS '원본 구분. 빈 칸은 NULL';
COMMENT ON COLUMN public.driving_records.shipper_name IS '원본 화주';
COMMENT ON COLUMN public.driving_records.region_1 IS '원본에서 첫 번째 지역 열. 출발지 등 업무 의미는 검토 후 확정';
COMMENT ON COLUMN public.driving_records.region_2 IS '원본에서 두 번째 지역 열. 도착지 등 업무 의미는 검토 후 확정';
COMMENT ON COLUMN public.driving_records.km IS '운행거리(km), 1~9999 정수. 과거 미상 기록은 NULL';
COMMENT ON COLUMN public.driving_records.shipping_line IS '원본 라인. 문자열로 보존';
COMMENT ON COLUMN public.driving_records.container_spec IS '원본 규격. 40 등의 값을 문자열로 보존';
COMMENT ON COLUMN public.driving_records.container_no IS '원본 CNTR 컨테이너 번호. 영문과 숫자로 구성된 문자열';
COMMENT ON COLUMN public.driving_records.charge_amount IS '원본 청구가액. 쉼표와 원 표시를 제거한 원 단위 정수';
COMMENT ON COLUMN public.driving_records.tax_amount IS '원본 행별 세액. 빈 칸은 NULL이며, 원본 확인 없이 0이나 10%로 채우지 않음';
COMMENT ON COLUMN public.driving_records.memo IS '원본 비고';
COMMENT ON COLUMN public.driving_records.vehicle_number IS '거래명세서 상단 차량번호. 문자열로 보존';
COMMENT ON COLUMN public.driving_records.recipient_name IS '거래명세서 상단 수신인 이름. 귀중 문구는 제외';
COMMENT ON COLUMN public.driving_records.created_at IS '실제 DB 등록 시각. 과거 운행일 operated_on과 별도로 기록';

CREATE INDEX driving_records_operated_on_idx ON public.driving_records (operated_on);

COMMIT;
