CREATE TABLE IF NOT EXISTS public.urea_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchased_on DATE NOT NULL
        DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date),
    merchant_name TEXT NOT NULL CHECK (length(btrim(merchant_name)) > 0),
    business_number TEXT,
    card_company TEXT,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    liters NUMERIC(12, 3) NOT NULL CHECK (liters > 0),
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON COLUMN public.urea_records.purchased_on IS '요소수 구매 날짜';
COMMENT ON COLUMN public.urea_records.merchant_name IS '상호명/대표자';
COMMENT ON COLUMN public.urea_records.business_number IS '사업자번호. 앞자리 0과 하이픈을 보존하는 문자열';
COMMENT ON COLUMN public.urea_records.card_company IS '카드사';
COMMENT ON COLUMN public.urea_records.unit_price IS '리터당 단가 (원)';
COMMENT ON COLUMN public.urea_records.liters IS '구매량 (리터)';
COMMENT ON COLUMN public.urea_records.total_amount IS '영수증 총액 (원)';

CREATE INDEX IF NOT EXISTS urea_records_purchased_on_id_idx
    ON public.urea_records (purchased_on, id);
